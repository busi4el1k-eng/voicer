// App-wide internationalisation. English is the default; players pick another
// language from the flag switcher in the dashboard. Strings are looked up by a
// dotted key with optional {placeholder} interpolation. Missing keys fall back
// to English, then to the raw key, so a half-translated dict never blanks out.

export const LOCALES = ["en", "es", "fr", "ru", "ro"] as const;
export type Locale = (typeof LOCALES)[number];

export const DEFAULT_LOCALE: Locale = "en";

// Native language name shown as the tooltip/aria-label in the flag menu. The
// flag itself is drawn as an SVG (see components/Flag.tsx) because emoji flags
// don't render on Windows.
export const LOCALE_META: Record<Locale, { label: string }> = {
  en: { label: "English" },
  es: { label: "Español" },
  fr: { label: "Français" },
  ru: { label: "Русский" },
  ro: { label: "Română" },
};

export function isLocale(v: string | null | undefined): v is Locale {
  return !!v && (LOCALES as readonly string[]).includes(v);
}

